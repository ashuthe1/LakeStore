#pragma once
#include "manifest.h"
#include "../options.h"
#include "../sstable/sstable_writer.h"
#include <vector>
#include <memory>

namespace lakestore {

class Compaction {
public:
    Compaction(const Options& options, int level, Version* version);

    // Adds input files to the compaction.
    // inputs_[0] = files from level_
    // inputs_[1] = overlapping files from level_ + 1
    void AddInputFiles(int level, const std::vector<FileMetaData*>& files);

    // Helper to generate the merged iterator for the background thread
    Iterator* MakeInputIterator();

    int level() const { return level_; }
    const std::vector<FileMetaData*>& inputs(int i) const { return inputs_[i]; }
    
    // Evaluates if a key can be safely dropped from the database
    bool ShouldDrop(const InternalKey& ikey, SequenceNumber smallest_snapshot);

    // Records the output files generated by the compaction thread
    void AddOutputFile(uint64_t file_number, uint64_t file_size, 
                       const InternalKey& smallest, const InternalKey& largest);

    // Builds the VersionEdit to atomically apply this compaction
    VersionEdit* edit() { return &edit_; }

private:
    Options options_;
    int level_;
    Version* input_version_;
    
    std::vector<FileMetaData*> inputs_[2];
    VersionEdit edit_;
    
    // State for ShouldDrop()
    std::string current_user_key_;
    bool has_current_user_key_ = false;
    SequenceNumber last_sequence_for_key_ = 0;
};

} // namespace lakestore